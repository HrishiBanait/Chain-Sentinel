#!/usr/bin/env node
// Generates docs/EVIDENCE.md from the scenario reports committed in docs/metrics/*.json.
// Nothing in the output is typed by hand: every figure comes from those files.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "docs", "metrics");
const files = existsSync(dir) ? readdirSync(dir).filter((f) => /^scenario-.*\.json$/.test(f)).sort() : [];

function latest(chaos) {
  const f = files.filter((x) => x.endsWith("-chaos.json") === chaos).pop();
  return f ? { file: f, report: JSON.parse(readFileSync(path.join(dir, f), "utf8")) } : null;
}
const pct = (x) => (x === null || x === undefined ? "n/a" : `${Math.round(x * 100)}%`);
const lat = (name, s) => (s ? `| ${name} | ${s.n} | ${s.min} | ${s.median} | ${s.p90} | ${s.max} |` : `| ${name} | not measured | | | | |`);

function section(title, run) {
  const out = [`## ${title}`, ""];
  if (!run) {
    out.push("No report found. Run `npm run scenario` in `backend/`, then `node scripts/gen-evidence.mjs`.", "");
    return out;
  }
  const { file, report: r } = run;
  const c = r.comparison;
  const base = file.replace(/\.json$/, "");
  const delta = (k) => (r.counters.after[k] ?? 0) - (r.counters.before[k] ?? 0);
  out.push(
    `Run at ${r.generatedAt} on ${r.network} (chain ID ${r.chainId}), commit ${r.commit ?? "unknown"}. Full report: [${base}.md](metrics/${base}.md). Raw data: [${file}](metrics/${file}).`,
    "",
    "| Measure | Value |",
    "|---|---|",
    `| Expected alerts | ${c.truePositives.length + c.missed.length} |`,
    `| Detected as expected | ${c.truePositives.length} |`,
    `| Missed | ${c.missed.length} |`,
    `| Unexpected alerts from scenario transactions | ${c.falsePositives.length} |`,
    `| Precision / recall | ${pct(c.precision)} / ${pct(c.recall)} |`,
    `| Cases that correctly produced no alert | ${c.silentCorrect} of ${c.silentTotal} |`,
    `| Severity mismatches | ${c.severityMismatches.length} |`,
    `| Alerts created / duplicate attempts ignored during the run | ${delta("alerts_created")} / ${delta("duplicate_alerts_ignored")} |`,
    `| Fixture back in its starting state afterwards | ${r.finalState.pristine ? "yes" : "no"} |`,
    "",
    "Latency in seconds (local clock, about ±2 s):",
    "",
    "| Stage | n | min | median | p90 | max |",
    "|---|---|---|---|---|---|",
    lat("Transaction mined to alert detected", r.latency.detect),
    lat("Alert detected to audit record published", r.latency.publish),
    lat("Alert detected to Telegram message sent", r.latency.notify),
    lat("Transaction mined to audit record published", r.latency.endToAudit),
    lat("Transaction mined to Telegram message sent", r.latency.endToNotify),
    ""
  );
  if (r.chaos) {
    out.push(
      `Fault injection: the monitor was killed with SIGKILL ${r.chaos.kills} time(s) and restarted ${r.chaos.restarts} time(s); catch-up after the last restart: ${
        r.chaos.catchUpSecs === null ? "did not finish within the timeout" : `${r.chaos.catchUpSecs} s`
      }. Latencies in this run include the outage.`,
      ""
    );
  }
  if (r.incomplete.length) out.push("Incomplete stages in this run:", "", ...r.incomplete.map((x) => `- ${x}`), "");
  return out;
}

const out = [
  "# Evidence",
  "",
  "This page is generated by `scripts/gen-evidence.mjs` from the reports in `docs/metrics/`. Do not edit it by hand.",
  "",
  "What these runs show: with events generated by a fixture token on MST Testnet, the pipeline produced the alerts that the rules specify, stayed silent on the cases that must be silent, and produced no duplicates. What they do not show: that real attacks would be detected, or that any alert is correct in the real world. The sample is small and comes from one public testnet, so treat the latencies as indicative.",
  "",
  ...section("Uninterrupted run", latest(false)),
  ...section("Run with fault injection", latest(true)),
  "## Reproduce",
  "",
  "    cd backend",
  "    npm run scenario -- --dry-run     # preflight and plan, sends nothing",
  "    npm run scenario                  # 16 testnet transactions, about 5 minutes",
  "    npm run scenario -- --chaos       # same, with the monitor killed twice",
  "    cd .. && node scripts/gen-evidence.mjs",
  "",
  "Start `npm run publish` and `npm run notify` first if you want the audit-record and Telegram stages measured; otherwise they are reported as not measured.",
  "",
];
writeFileSync(path.join(root, "docs", "EVIDENCE.md"), out.join("\n"));
console.log(`wrote docs/EVIDENCE.md from ${files.length} report file(s)`);
